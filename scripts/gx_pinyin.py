#!/usr/bin/env python3
"""生成 Ghostty GX 模糊匹配用的拼音首字母表 src/gx/pinyin/initials.zig。

用法：
  python scripts/gx_pinyin.py --download       缓存里没有源数据时先下载钉版 pinyin-data，再生成并写入
  python scripts/gx_pinyin.py [--source PATH]  从源数据生成并写入（内容不变时不改文件）；PATH 是
                                               pinyin-data 的目录或发布包 .tar.gz，默认取缓存目录
  python scripts/gx_pinyin.py --check          只读校验已提交的首字母表（见下文「校验」）
  可选 --root PATH（测试用，默认取脚本所在仓库）

数据来源：pinyin-data 0.15.0（https://github.com/mozillazg/pinyin-data，MIT 许可，
Copyright (c) 2016 mozillazg；读音来自 Unicode Unihan 数据库，Unicode License V3）。两份许可原文
放在生成物旁的 src/gx/pinyin/pinyin-data-LICENSE.txt 与 Unicode-LICENSE.txt，升级钉版时一并
核对；随包分发时 THIRD-PARTY 声明要同时列出这两份许可。只用三个文件，按内容 sha256 钉版
（SOURCE_FILES），下载的发布包解出后逐个校验；缓存在 .local/cache/pinyin-data-<版本>/。

首字母表覆盖 CJK 统一汉字基本区 U+4E00..U+9FFF：
  - primary：pinyin.txt 第一个读音（最常用读音）的首字母，没有读音的码位记为 `.`；
  - extra：《通用规范汉字字典》(kTGHZ2013.txt) 与《现代汉语词典》(kXHC1983.txt) 的其余读音带来的
    其他首字母（多音字取并集，如「乐」l、y）。不取《汉语大字典》等只收古音的来源，免得生僻读音
    造成误匹配（「重」不会多出 t）。
首字母是读音去掉声调与附加符号后的第一个字母（ḿ、ň、ǹ 取 m、n），必须是 a..z。

校验：生成物第二行记录格式版本、三个源文件与生成物其余部分的 sha256。--check 总是校验格式版本、
源文件摘要与脚本钉的一致、其余部分未被改动；本机有源数据（--source 或缓存）时再重新生成逐字节比对。

输出确定：LF、无时间戳，同一输入在任何平台得到同样的字节；CRLF 检出的源文件与生成物视同 LF。
退出码：0 成功（或 --check 通过）；1 --check 时生成物缺失、被改动或过期；2 用法错误、源数据缺失或不合法。
"""

from __future__ import annotations

import argparse
import hashlib
import io
import re
import sys
import tarfile
import unicodedata
import urllib.request
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
OUTPUT = "src/gx/pinyin/initials.zig"
FORMAT = 1
FIRST = 0x4E00
LAST = 0x9FFF
LINE_WIDTH = 64

SOURCE_VERSION = "0.15.0"
SOURCE_URL = f"https://github.com/mozillazg/pinyin-data/archive/refs/tags/v{SOURCE_VERSION}.tar.gz"
CACHE_DIR = f".local/cache/pinyin-data-{SOURCE_VERSION}"
PRIMARY_FILE = "pinyin.txt"
EXTRA_FILES = ("kTGHZ2013.txt", "kXHC1983.txt")
SOURCE_FILES = {
    "pinyin.txt": "6170ab4ff7c9740fe765b1d35e6d3ad43554dd02874199388db513c44dcddf9d",
    "kTGHZ2013.txt": "83be5ecdfe0b8fcc1202ae45882a2f983c013db87ba68369d94a4dad775382bb",
    "kXHC1983.txt": "7ade5b5750c92d39dec2151075ebcca323afe6af452349f54438d950b1dd4eeb",
}

META_PREFIX = "// gx-pinyin:"
META_RE = re.compile(r"^// gx-pinyin: format (\d+); sources (.+); body ([0-9a-f]{64})$")
LINE_RE = re.compile(r"^U\+([0-9A-Fa-f]{4,6})\s*:\s*(.*)$")

HEADER = f"""\
//! Pinyin initials of the CJK Unified Ideographs U+4E00..U+9FFF, for
//! matching Chinese text by the first letters of its readings: the
//! letter of the most common reading of each character, and the other
//! letters its modern readings start with.
//!
//! Generated by `python scripts/gx_pinyin.py` from pinyin-data
//! {SOURCE_VERSION} (https://github.com/mozillazg/pinyin-data, MIT License,
//! Copyright (c) 2016 mozillazg), whose readings come from the Unicode
//! Unihan database (Unicode License V3); the license texts are in
//! `pinyin-data-LICENSE.txt` and `Unicode-LICENSE.txt` next to this
//! file. Do not edit by hand.
"""


class SourceError(ValueError):
    """Source data that is missing, does not match its pin or cannot be parsed."""


@dataclass
class Table:
    """The initials of FIRST..LAST: one primary letter (or '.') per code point and the extra letters."""

    primary: str
    extra: dict[int, str]


def initial_of(reading: str, where: str = "") -> str:
    """The first letter of a pinyin reading without tone marks (`lǜ` -> `l`, `ḿ` -> `m`)."""
    base = "".join(c for c in unicodedata.normalize("NFD", reading) if not unicodedata.combining(c))
    letter = base[:1].lower()
    if not ("a" <= letter <= "z"):
        raise SourceError(f"{where}: reading {reading!r} does not start with a letter")
    return letter


def parse_readings(text: str, name: str) -> dict[int, list[str]]:
    """`U+XXXX: reading,reading  # hanzi` lines -> code point -> readings (commas or spaces separate them)."""
    readings: dict[int, list[str]] = {}
    for number, raw in enumerate(text.splitlines(), start=1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        match = LINE_RE.match(line)
        if match is None:
            raise SourceError(f"{name}:{number}: cannot parse line {raw!r}")
        values = [value for value in re.split(r"[,\s]+", match.group(2)) if value]
        if not values:
            raise SourceError(f"{name}:{number}: no reading in line {raw!r}")
        code_point = int(match.group(1), 16)
        if code_point in readings:
            raise SourceError(f"{name}:{number}: duplicate code point U+{code_point:04X}")
        readings[code_point] = values
    return readings


def build_table(primary: dict[int, list[str]], extras: list[dict[int, list[str]]]) -> Table:
    letters: list[str] = []
    extra: dict[int, str] = {}
    for code_point in range(FIRST, LAST + 1):
        readings = primary.get(code_point)
        if not readings:
            letters.append(".")
            continue
        where = f"U+{code_point:04X}"
        first = initial_of(readings[0], where)
        letters.append(first)
        others = {initial_of(reading, where) for source in extras for reading in source.get(code_point, [])}
        others.discard(first)
        if others:
            extra[code_point] = "".join(sorted(others))
    return Table(primary="".join(letters), extra=extra)


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def body_lines(table: Table) -> list[str]:
    lines = [
        "",
        "/// The first code point of `primary`.",
        f"pub const first = 0x{FIRST:04X};",
        "",
        "/// The initial of the most common reading of each code point from",
        "/// `first` on (`a`..`z`), `.` for code points without a reading.",
        "pub const primary =",
    ]
    chunks = [table.primary[i : i + LINE_WIDTH] for i in range(0, len(table.primary), LINE_WIDTH)]
    for index, chunk in enumerate(chunks):
        end = ";" if index == len(chunks) - 1 else " ++"
        lines.append(f'    "{chunk}"{end} // U+{FIRST + index * LINE_WIDTH:04X}')
    lines += [
        "",
        "/// The code points whose other modern readings start with other",
        "/// letters, ascending, and those letters.",
        "pub const extra = [_]struct { u16, []const u8 }{",
    ]
    for code_point in sorted(table.extra):
        lines.append(f'    .{{ 0x{code_point:04X}, "{table.extra[code_point]}" }}, // {chr(code_point)}')
    lines.append("};")
    return lines


def meta_line(sources: dict[str, str], body: str) -> str:
    listed = ", ".join(f"{name} {digest}" for name, digest in sorted(sources.items()))
    return f"{META_PREFIX} format {FORMAT}; sources {listed}; body {sha256_text(body)}"


def split_meta(text: str) -> tuple[str | None, str]:
    """The meta line of a generated file and the rest of the file without it."""
    lines = text.split("\n")
    for index, line in enumerate(lines):
        if line.startswith(META_PREFIX):
            return line, "\n".join(lines[:index] + lines[index + 1 :])
    return None, text


def render(table: Table, sources: dict[str, str]) -> str:
    body = HEADER + "\n".join(body_lines(table)) + "\n"
    header_lines = HEADER.count("\n")
    lines = body.split("\n")
    lines.insert(header_lines, meta_line(sources, body))
    return "\n".join(lines)


def verify(text: str, pins: dict[str, str] | None = None) -> list[str]:
    """Problems of a generated file that can be found without the source data."""
    pins = SOURCE_FILES if pins is None else pins
    meta, rest = split_meta(normalize(text))
    if meta is None:
        return [f"{OUTPUT} 没有 `{META_PREFIX}` 元数据行"]
    match = META_RE.match(meta)
    if match is None:
        return [f"{OUTPUT} 的元数据行无法解析：{meta!r}"]
    problems = []
    if int(match.group(1)) != FORMAT:
        problems.append(f"{OUTPUT} 是格式 {match.group(1)} 生成的，脚本是格式 {FORMAT}")
    expected = ", ".join(f"{name} {digest}" for name, digest in sorted(pins.items()))
    if match.group(2) != expected:
        problems.append(f"{OUTPUT} 的源文件摘要与脚本钉的 pinyin-data {SOURCE_VERSION} 不一致")
    if match.group(3) != sha256_text(rest):
        problems.append(f"{OUTPUT} 在生成后被改动过（正文摘要不符）")
    return problems


def normalize(text: str) -> str:
    return text.replace("\r\n", "\n")


def read_sources(path: Path, pins: dict[str, str] | None = None) -> dict[str, str]:
    """The pinned source files from a pinyin-data directory or release tarball, checked against their pins."""
    pins = SOURCE_FILES if pins is None else pins
    raw: dict[str, bytes] = {}
    if path.is_dir():
        for name in pins:
            try:
                raw[name] = (path / name).read_bytes()
            except FileNotFoundError:
                raise SourceError(f"{path} 里没有 {name}") from None
    elif path.is_file():
        raw = read_tarball(path.read_bytes(), pins)
    else:
        raise SourceError(f"源数据 {path} 不存在，先运行 python scripts/gx_pinyin.py --download")
    texts: dict[str, str] = {}
    for name, digest in pins.items():
        actual = hashlib.sha256(raw[name]).hexdigest()
        if actual != digest:
            raise SourceError(f"{name} 的 sha256 是 {actual}，脚本钉的是 {digest}")
        try:
            texts[name] = normalize(raw[name].decode("utf-8-sig"))
        except UnicodeDecodeError as err:
            raise SourceError(f"{name} 不是合法的 UTF-8：{err}") from None
    return texts


def read_tarball(data: bytes, pins: dict[str, str]) -> dict[str, bytes]:
    """The pinned files from the top directory of a release tarball."""
    found: dict[str, bytes] = {}
    try:
        with tarfile.open(fileobj=io.BytesIO(data), mode="r:*") as archive:
            for member in archive.getmembers():
                parts = member.name.split("/")
                if len(parts) != 2 or parts[1] not in pins or not member.isfile():
                    continue
                handle = archive.extractfile(member)
                if handle is not None:
                    found[parts[1]] = handle.read()
    except tarfile.TarError as err:
        raise SourceError(f"无法读取发布包：{err}") from None
    missing = sorted(set(pins) - set(found))
    if missing:
        raise SourceError(f"发布包里没有 {', '.join(missing)}")
    return found


def download(cache: Path, pins: dict[str, str] | None = None, url: str = SOURCE_URL) -> None:
    """Fetch the release tarball and keep the pinned files (checked) in `cache`."""
    pins = SOURCE_FILES if pins is None else pins
    print(f"[gx-pinyin] 下载 {url}")
    try:
        with urllib.request.urlopen(url, timeout=120) as response:
            data = response.read()
    except OSError as err:
        raise SourceError(f"下载 {url} 失败：{err}") from None
    files = read_tarball(data, pins)
    for name, digest in pins.items():
        actual = hashlib.sha256(files[name]).hexdigest()
        if actual != digest:
            raise SourceError(f"下载的 {name} 的 sha256 是 {actual}，脚本钉的是 {digest}")
    cache.mkdir(parents=True, exist_ok=True)
    for name, content in files.items():
        (cache / name).write_bytes(content)


def has_sources(directory: Path, pins: dict[str, str] | None = None) -> bool:
    pins = SOURCE_FILES if pins is None else pins
    return all((directory / name).is_file() for name in pins)


def generate(texts: dict[str, str], pins: dict[str, str] | None = None) -> str:
    pins = SOURCE_FILES if pins is None else pins
    primary = parse_readings(texts[PRIMARY_FILE], PRIMARY_FILE)
    extras = [parse_readings(texts[name], name) for name in EXTRA_FILES]
    return render(build_table(primary, extras), pins)


def _utf8_stdio() -> None:
    for stream in (sys.stdout, sys.stderr):
        reconfigure = getattr(stream, "reconfigure", None)
        if reconfigure is not None:
            reconfigure(encoding="utf-8", errors="replace")


def main(argv: list[str] | None = None) -> int:
    _utf8_stdio()
    parser = argparse.ArgumentParser(description="生成 src/gx/pinyin/initials.zig（拼音首字母表）")
    parser.add_argument("--check", action="store_true", help="只校验首字母表，不写入")
    parser.add_argument("--download", action="store_true", help="缓存里没有源数据时先下载钉版 pinyin-data")
    parser.add_argument("--source", type=Path, help="pinyin-data 目录或发布包，默认取缓存目录")
    parser.add_argument("--root", type=Path, default=REPO_ROOT, help="仓库根目录（测试用）")
    args = parser.parse_args(argv)
    if args.check and args.download:
        parser.error("--check 不下载，与 --download 不能同时使用")

    root: Path = args.root
    output = root / OUTPUT
    cache = root / CACHE_DIR
    source: Path = args.source if args.source is not None else cache
    try:
        current = normalize(output.read_text(encoding="utf-8"))
    except FileNotFoundError:
        current = None

    if args.check:
        if current is None:
            print(f"[gx-pinyin] {OUTPUT} 缺失，运行 python scripts/gx_pinyin.py --download 生成", file=sys.stderr)
            return 1
        problems = verify(current)
        if problems:
            for problem in problems:
                print(f"[gx-pinyin] {problem}", file=sys.stderr)
            print("[gx-pinyin] 运行 python scripts/gx_pinyin.py --download 重新生成", file=sys.stderr)
            return 1
        if args.source is None and not has_sources(cache):
            print(f"[gx-pinyin] {OUTPUT} 未被改动（本机没有源数据，未重新生成比对）")
            return 0
        try:
            generated = generate(read_sources(source))
        except SourceError as err:
            print(f"[gx-pinyin] {err}", file=sys.stderr)
            return 2
        if generated != current:
            print(f"[gx-pinyin] {OUTPUT} 与源数据不一致，运行 python scripts/gx_pinyin.py 重新生成", file=sys.stderr)
            return 1
        print(f"[gx-pinyin] {OUTPUT} 是最新的")
        return 0

    try:
        if args.download and args.source is None and not has_sources(cache):
            download(cache)
        generated = generate(read_sources(source))
    except SourceError as err:
        print(f"[gx-pinyin] {err}", file=sys.stderr)
        return 2
    if current == generated:
        print(f"[gx-pinyin] {OUTPUT} 无变化")
        return 0
    output.parent.mkdir(parents=True, exist_ok=True)
    with open(output, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(generated)
    print(f"[gx-pinyin] 已写入 {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
